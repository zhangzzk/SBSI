def qtable(name, d):
    """Quantile fingerprint of a population, printed one row per column."""
    print(f"  {name}")
    print(f"    {'column':>16} {'N':>12} {'p01':>8} {'p16':>8} {'p50':>8} {'p84':>8} {'p99':>8} "
          f"{'mean':>8}")
    for c, v in d.items():
        v = np.asarray(v, float)
        v = v[np.isfinite(v)]
        q = np.percentile(v, [1, 16, 50, 84, 99]) if len(v) else [np.nan] * 5
        print(f"    {c:>16} {len(v):>12,} {q[0]:>8.3f} {q[1]:>8.3f} {q[2]:>8.3f} {q[3]:>8.3f} "
              f"{q[4]:>8.3f} {np.mean(v) if len(v) else np.nan:>8.3f}")


def population_check(base, train_cat, train_max_rows, t0):
    """PART A: is the constgold eval population the same one the flow was trained on?

    Both sides apply source_select_selection(DEFAULT_SELECTION_CUTS) -- true mag in [18,28], true Re
    in [0.1,1.5], neighbour distance < 5" (or unneighboured). Identical cuts do NOT guarantee
    identical populations: the two sims can differ in depth and crowding. Compare the distributions.
    """
    print("\n" + "=" * 78)
    print("PART A -- training population vs constgold evaluation population")
    print("=" * 78, flush=True)
    print(f"  cuts applied on BOTH sides: DEFAULT_SELECTION_CUTS = {DEFAULT_SELECTION_CUTS}")
    print("    -> [1] true mag r_input_p in (18,28) ; [3] true Re_input_p in (0.1,1.5) ;"
          " [4] distance<5\" or ~neighbored")

    cols = ["r_input_p", "Re_input_p", "distance", "neighbored", "sersic_n_input_p"]
    parts, n = [], 0
    with ipc.open_file(pa.memory_map(train_cat)) as r:
        use = [c for c in cols if c in set(r.schema.names)]
        for bi in range(r.num_record_batches):
            b = pa.Table.from_batches([r.get_batch(bi)]).select(use).to_pandas()
            parts.append(b)
            n += len(b)
            if n >= train_max_rows:
                break
    tr = pd.concat(parts, ignore_index=True).iloc[:train_max_rows]
    del parts
    print(f"  training catalogue: {os.path.basename(train_cat)}  read {len(tr):,} rows "
          f"({time.time()-t0:.0f}s)", flush=True)
    tr = source_select_selection(tr, cuts=DEFAULT_SELECTION_CUTS)
    print(f"  after cuts: {len(tr):,}", flush=True)

    qtable("TRAINING (det_meas g=0 leg, the flow's own sample)",
           {c: tr[c] for c in ("r_input_p", "Re_input_p", "sersic_n_input_p")})
    qtable("CONSTGOLD (this evaluation)",
           {c: base[c] for c in ("r_input_p", "Re_input_p", "sersic_n_input_p")})
    print(f"    neighboured fraction: training {tr['neighbored'].mean():.3f}   "
          f"constgold {base['neighbored'].mean():.3f}")

    # how much of the eval sample sits outside the bulk of training support
    for c in ("r_input_p", "Re_input_p"):
        lo, hi = np.percentile(tr[c].to_numpy(float), [0.5, 99.5])
        out = float(np.mean((base[c].to_numpy(float) < lo) | (base[c].to_numpy(float) > hi)))
        print(f"    {c}: {out:.3%} of constgold outside training [p0.5,p99.5]=({lo:.3f},{hi:.3f})")
    del tr


def slope(dx, p):
    """b = Cov(dx, p)/Var(p): the pinned coupling coefficient, given dx already divided by 2g."""
    ok = np.isfinite(dx) & np.isfinite(p)
    if ok.sum() < 50:
        return np.nan, int(ok.sum())
    d, q = dx[ok], p[ok]
    v = q.var()
    return (float(np.cov(d, q, bias=True)[0, 1] / v) if v > 0 else np.nan), int(ok.sum())


def coupling_report(tag, dmag, dlsz, p_int, base, cz, g):
    """PART B/C: measured coupling vs the pinned target, globally and per (flux, size) cell."""
    bm, nm = slope(dmag / (2 * g), p_int)
    bs, ns = slope(dlsz / (2 * g), p_int)
    print(f"\n  [{tag}]  GLOBAL   b_mag = {bm:+.4f}   b_size = {bs:+.4f}   (N={nm:,})")
    print(f"           pinned    b_mag = {float(cz['b_mag_global']):+.4f}   "
          f"b_size = {float(cz['b_size_global']):+.4f}   <- target the flow was trained to")

    ef, es = cz["edges_flux"], cz["edges_size"]
    cnt = cz["counts"]                       # (nf, ns, nb)
    w = cnt.sum(axis=2)
    with np.errstate(invalid="ignore", divide="ignore"):
        tgt_m = (cz["coupling_mag"] * cnt).sum(axis=2) / np.where(w > 0, w, np.nan)
        tgt_s = (cz["coupling_size"] * cnt).sum(axis=2) / np.where(w > 0, w, np.nan)

    fi = np.clip(np.digitize(base["r_input_p"].to_numpy(float), ef[1:-1]), 0, len(ef) - 2)
    si = np.clip(np.digitize(base["Re_input_p"].to_numpy(float), es[1:-1]), 0, len(es) - 2)
    print(f"    {'true mag bin':>16} {'true Re bin':>14} {'N':>10} "
          f"{'b_mag':>8} {'pin':>8} | {'b_size':>8} {'pin':>8}")
    for a in range(len(ef) - 1):
        for b_ in range(len(es) - 1):
            m = (fi == a) & (si == b_)
            if m.sum() < 5000:
                continue
            bmv, _ = slope((dmag / (2 * g))[m], p_int[m])
            bsv, _ = slope((dlsz / (2 * g))[m], p_int[m])
            print(f"    {ef[a]:>7.2f}-{ef[a+1]:<8.2f} {es[b_]:>6.2f}-{es[b_+1]:<7.2f} "
                  f"{int(m.sum()):>10,} {bmv:>8.4f} {tgt_m[a, b_]:>8.4f} | "
                  f"{bsv:>8.4f} {tgt_s[a, b_]:>8.4f}")
    return bm, bs


def boundary_report(base, p_int, dmag, dlsz, g, mag_cuts, size_cuts, px):
    """PART D: the two factors the moving-boundary response factorises into, at each threshold.

    R_sel ~= density(T) * < p_int * (-Delta x) >_{x near T} / (2g) / keep_fraction
    Splitting it says whether a sim/model mismatch is the coupling (second factor) or the measured
    distribution (first factor).
    """
    print("\n" + "=" * 78)
    print("PART D -- moving-boundary decomposition on the SIM (constgold)")
    print("=" * 78)
    print(f"  {'cut':>12} {'keep%':>7} {'dens/unit':>10} {'<p*(-dx)>/2g':>14} "
          f"{'product':>10} {'R_sel exact':>12}")
    mag = base["measured_mag_auto_plus"].to_numpy(float)
    lsz = np.log(np.maximum(base["measured_flux_radius_plus"].to_numpy(float), 1e-6))
    for kind, thrs in (("mag", mag_cuts), ("size", size_cuts)):
        for c in thrs:
            if kind == "mag":
                x, dx, T, w, keep_hi = mag, dmag, float(c), 0.05, False
            else:
                x, dx, T, w = lsz, dlsz, float(np.log(float(c) / px)), 0.02
                keep_hi = True
            near = np.abs(x - T) < w
            dens = float(near.mean()) / (2 * w)
            drv = float(np.mean(p_int[near] * (-dx[near]))) / (2 * g) if near.sum() > 50 else np.nan
            if keep_hi:
                pp, pm = x > T, (x - dx) > T
            else:
                pp, pm = x < T, (x - dx) < T
            keep = 0.5 * (pp.mean() + pm.mean())
            exact = (p_int[pp].mean() - p_int[pm].mean()) / (2 * g)
            # keep-low: a POSITIVE dx pushes an object out of the sample, so the boundary term
            # enters with the opposite sign to the keep-high case.
            sgn = -1.0 if keep_hi else 1.0
            print(f"  {kind}{c:>8g} {keep*100:>7.2f} {dens:>10.4f} {drv:>+14.5f} "
                  f"{sgn*dens*drv/max(keep,1e-9):>+10.5f} {exact:>+12.5f}")


@torch.no_grad()
def flow_deltas(bundle, legs, n_samples, batch_size, flow_seed, chunk, n):
    """Per-object mean measured mag / log-size in each leg, common random numbers across legs."""
    out = {}
    for leg in (0, 1):
        mg = np.empty(n, dtype=np.float64)
        sz = np.empty(n, dtype=np.float64)
        for cs in range(0, n, chunk):
            sl = slice(cs, min(cs + chunk, n))
            torch.manual_seed(flow_seed + cs)
            if torch.cuda.is_available():
                torch.cuda.manual_seed_all(flow_seed + cs)
            d = bundle.sample(legs[leg].iloc[sl], n_samples=n_samples, batch_size=batch_size)
            mg[sl] = np.nanmean(d[:, :, 2], axis=1)
            sz[sl] = np.nanmean(d[:, :, 3], axis=1)
        out[leg] = (mg, sz)
    return out[1][0] - out[0][0], out[1][1] - out[0][1]


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
