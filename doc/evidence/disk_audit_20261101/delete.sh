#SBATCH -p cluster
#SBATCH -c 4
#SBATCH --mem 4G
#SBATCH -t 08:00:00
#SBATCH -J t1delete
#SBATCH -o /home/z/Zekang.Zhang/.claude/jobs/be02074a/tmp/mm/cleanup/delete_%j.log
# Tier-1 cleanup approved by the owner 2026-11-01. Deletes exactly the manifest lists from job 17641482.
set -euo pipefail
O=/home/z/Zekang.Zhang/.claude/jobs/be02074a/tmp/mm/cleanup
CP=/project/ls-gruen/users/zekang.zhang/sbsi/catalogue_prior
U=/project/ls-gruen/users/zekang.zhang
cd $O
echo "df before"; df -h $U | tail -1
lfs quota -u zekang.zhang /project 2>/dev/null | head -4 || true

# --- safety checks: refuse to delete anything outside the approved patterns ---
cut -f2 files.txt > file_paths.txt
bad=$(grep -v -c -E "^$CP/(galsbi_pair1m_20261012|galsbi_blind100k_20261003|galsbi_mock500k_20261006|galsbi_faintg05_20261013|galsbi_blind10k_20261003|galsbi_twin100k_20261005|galsbi_constgold100k_20261025|optimize_20261011|galsbi_mock10k_20261002|galsbi_throughput_20261002|galsbi_bright_mh_20261002|galsbi_speed_20261003|galsbi_speedup_20261003|galsbi_concurrency_20261026_v2|galsbi_mh1024_20261002|galsbi_bias238_20261002|galsbi_long_mh_20261001|galsbi_light_transfer_20261002|galsbi_cpu_scaling_20261002|galsbi_tempering_20261002|galsbi_concurrency_20261026_v1)/.*/(chain|local_profiles|final_scenes)\.npz$" file_paths.txt || true)
[ "$bad" -eq 0 ] || { echo "ABORT: $bad file paths outside approved patterns"; exit 1; }
bad=$(grep -v -c -E "^$U/lsst_sims_fs2_25876_(anchorblend_eachpair_g._rank.._pilot_c400-409|anchorblend_coherent_g2_pilot_c400-409|anchorblend_smoke|v22cgq3_c48-139_[a-z]+_failed1563....|v22decomp_rankpilot_rank[0-9]+|v22decomp_pilot_[a-z0-9]+|v22cgq3_pilot_[a-z]+|constant_REPRO)$" stale_dirs.txt || true)
[ "$bad" -eq 0 ] || { echo "ABORT: $bad stale dirs outside approved patterns"; exit 1; }
bad=$(grep -v -c -E "^$U/sbsi_catalogues/[A-Za-z0-9_.]+\.feather\.oldcats_bak$" bak_files.txt || true)
[ "$bad" -eq 0 ] || { echo "ABORT: bak list"; exit 1; }
nonpyc=$(find $CP/galsbi_concurrency_20261026_v1/bytecode $CP/galsbi_concurrency_20261026_v2/bytecode $CP/galsbi_concurrency_20261026_v1/__pycache__ $CP/galsbi_concurrency_20261026_v2/__pycache__ -type f ! -name '*.pyc' | wc -l)
echo "non-pyc files in bytecode/__pycache__: $nonpyc (left in place)"
echo "checks passed"

# --- sampler arrays ---
xargs -d '\n' -a file_paths.txt -n 1000 rm -f
left=$(xargs -d '\n' -a file_paths.txt -n 1000 ls 2>/dev/null | wc -l || true)
echo "sampler files remaining: $left"

# --- generated bytecode (pyc only), then empty dirs ---
for d in $CP/galsbi_concurrency_20261026_v1 $CP/galsbi_concurrency_20261026_v2; do
  find $d/bytecode $d/__pycache__ -type f -name '*.pyc' -delete
  find $d/bytecode $d/__pycache__ -depth -type d -empty -delete
done
echo "bytecode done"

# --- stale sim dirs and backup catalogues ---
xargs -d '\n' -a stale_dirs.txt rm -rf
xargs -d '\n' -a bak_files.txt rm -f
echo "stale dirs remaining: $(xargs -d '\n' -a stale_dirs.txt ls -d 2>/dev/null | wc -l || true)"
echo "bak remaining: $(xargs -d '\n' -a bak_files.txt ls 2>/dev/null | wc -l || true)"

echo "df after"; df -h $U | tail -1
lfs quota -u zekang.zhang /project 2>/dev/null | head -4 || true
echo DELETE_DONE
