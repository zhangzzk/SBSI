"""WHY is the flow's magnitude-cut selection response flat? Measure the one channel that carries it.

BACKGROUND. The Gold-V2 flow is never conditioned on g. Its ONLY shear channel into the measured
observables is the mean head's dependence on the intrinsic shape, and the residual flow is explicitly
blind to it (`--flow-blind-features e1_input_p e2_input_p`). During training that channel is PINNED
by the spin-2 orientation-coupling loss (lam_theta=500) to

    d<measured_mag_auto>/dg      = b_mag  * e_int
    d<measured_log_flux_radius>/dg = b_size * e_int

with b_mag/b_size read per (flux, size, crowd) cell from --coupling-npz. So the model's whole
moving-boundary selection response is generated by those two numbers. Globally the target file
carries b_size=0.490 but b_mag=0.025 -- a 19x weaker magnitude coupling.

Those targets were measured on the det_meas HALF-SHEAR sim at g=0.05. The selection figure evaluates
on constgold at g=+/-0.02. This script measures the SAME coefficients directly on constgold and on
the flow, so the three can be compared like for like:

    b_x = slope of [ x_plus - x_minus ] / (2g)  regressed on  p_int = e_int . ghat

(exactly the pinned quantity: with ghat=(1,0), Delta x = b_x * e_int * 2g). Reported globally and in
the coupling file's own (flux, size) cells.

It also reports, per cut threshold, the two factors the moving-boundary response actually factorises
into -- the density of objects AT the boundary and the boundary-local mean of p_int * (-Delta x) --
so a mismatch can be attributed to the wrong coupling vs the wrong measured distribution.

PART A additionally compares the TRAINING population to the constgold evaluation population under the
identical `source_select_selection(DEFAULT_SELECTION_CUTS)` both sides apply, to confirm the flow is
not being asked to extrapolate off its training support.

Nothing is trained or fitted. constgold stays EVAL-ONLY.
"""
